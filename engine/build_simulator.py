    shell = open(os.path.join(HERE, "shell.html"), encoding="utf-8").read()
    # The blurred room background. Derived from a source image rather than authored,
    # so it lives beside the shell as a data URI rather than inline in it; the command
    # that regenerates it is in a comment at the top of the .room rule.
    room_bg = open(os.path.join(HERE, "room-bg.txt"), encoding="utf-8").read().strip()
    # Welcome screen assets, substituted the same way. Derived from assets/, not
    # authored; see engine/README-assets.md for the regeneration commands.
    hero_bg = open(os.path.join(HERE, "hero-bg.txt"), encoding="utf-8").read().strip()
    avatar_m = open(os.path.join(HERE, "avatar-male.txt"), encoding="utf-8").read().strip()
    avatar_f = open(os.path.join(HERE, "avatar-female.txt"), encoding="utf-8").read().strip()
    # The nurse's portrait, beside the line she speaks. Unlike the patient silhouettes
    # this is a full-colour image rather than a CSS mask, because it is a person rather
    # than a diagram of one, and the interface has no other picture of a human in it.
    # Source kept beside it so the crop can be redone rather than reverse-engineered:
    #   python3 -c "from PIL import Image; im=Image.open('assets/nurse-avatar-source.png');\
    #     im.quantize(colors=96, method=Image.FASTOCTREE).convert('RGBA')\
    #       .save('/tmp/a.png', optimize=True)"
    #   base64 -w0 /tmp/a.png > nurse-avatar.txt
    # 240px square, quantised to 96 colours: 32 KB, against 56 KB for the unquantised
    # crop, and the difference is invisible at the 62px it renders at.
    nurse_av = open(os.path.join(HERE, "nurse-avatar.txt"), encoding="utf-8").read().strip()
    # Ward ambience, base64 mp3. Derived from the author's recording by
    # engine/assets/make-ambience.py: 45 seconds taken from a steady stretch, the tail
    # crossfaded onto the head so it repeats without a seam, peak-normalised so that the
    # gain figure in SHARED.audio.rhythm's neighbour LEVEL block means something, and
    # encoded mono at 48 kbps because it plays at about -51 dBFS and nobody will ever
    # hear the codec. Optional: a checkout without it builds a simulator with a silent
    # room and no other difference, which matters because it is by far the largest single
    # asset in the file.
    amb_path = os.path.join(HERE, "ambience.txt")
    ambience = (open(amb_path, encoding="utf-8").read().strip() if os.path.exists(amb_path) else "")
    # semantic.js declares `const SEM` and ui.js registers a listener on it at top
    # level, so it MUST come before ui.js. Reversed, the bundle throws before the
    # first render and the page is blank.
    # audio.js is fenced separately so the test harness can evaluate it without the
    # engine, and the engine without it. The interval model is a claim about physiology
    # and has to be assertable.
    # monitor.js declares `const MONITOR` and audio.js calls MONITOR.onBeat at its own
    # top level, so it MUST come before audio.js: the beat clock the two share lives in
    # the monitor. Fenced for the same reason audio.js is, because the waveform makes
    # claims (a QRS duration that renders as authored, a mean interval that is the
    # authored rate) that the harness has to be able to assert.
    # The patient figure. patient-art.json is derived from the avataaars library by
    # engine/assets/avataaars/extract.js and is injected as a constant ahead of patient.js,
    # inside the same fence, so the harness can evaluate the pair without the page. The MIT
    # licence requires its notice to travel with the artwork, so the licence text goes into
    # every file the artwork goes into. patient.js depends on nothing else in the bundle
    # and ui.js calls it from the frame loop, so the only ordering rule is: before ui.js.
    # Optional in the same way the ambience is: without the art file PATIENT.available is
    # false, the stage stays empty and nothing else changes.
    art_path = os.path.join(HERE, "patient-art.json")
    art = json.load(open(art_path, encoding="utf-8")) if os.path.exists(art_path) else None
    notice = ("Patient artwork: avataaars, https://github.com/fangpenlin/avataaars\n" +
              open(os.path.join(HERE, "assets", "avataaars", "LICENSE"), encoding="utf-8").read()).replace("*/", "* /")
    patient_js = open(os.path.join(HERE, "patient.js"), encoding="utf-8").read()
    patient_block = ("/*\n" + notice + "\n*/\nconst PATIENT_ART=" + jsafe(art) + ";\n" + patient_js)
    lab_src = os.path.join(HERE, "patient-lab.html")
    if art and os.path.exists(lab_src):
        lab = open(lab_src, encoding="utf-8").read()
        lab = lab.replace("__PATIENT_NOTICE__", notice.replace("--", "- -"))
        lab = lab.replace("__PATIENT_BASES__", jsafe(shared["patient"]["base"]))
        lab = lab.replace("__PATIENT_ART__", jsafe(art)).replace("__PATIENT_JS__", patient_js)
        os.makedirs(BUILD_DIR, exist_ok=True)
        open(os.path.join(BUILD_DIR, "patient-lab.html"), "w", encoding="utf-8", newline="\n").write(lab)
    bundle = ("/*__ENGINE_START__*/\n" + open(os.path.join(HERE, "engine.js"), encoding="utf-8").read() +
              "\n/*__ENGINE_END__*/\n"
              "/*__PATIENT_START__*/\n" + patient_block +
              "\n/*__PATIENT_END__*/\n"
              "/*__MONITOR_START__*/\n" + open(os.path.join(HERE, "monitor.js"), encoding="utf-8").read() +
              "\n/*__MONITOR_END__*/\n"
              "/*__AUDIO_START__*/\n" + open(os.path.join(HERE, "audio.js"), encoding="utf-8").read() +
              "\n/*__AUDIO_END__*/\n" +
              "\n" + open(os.path.join(HERE, "semantic.js"), encoding="utf-8").read() +
              # voice.js declares `const VOICE` and ui.js calls VOICE.build from bindCase,
              # which boot() reaches at the end of ui.js, so it MUST come before ui.js for
              # the same reason semantic.js must. Its own top level touches nothing from
              # ui.js; the calls it makes into ui.js (log, render, inCase) run from
              # handlers, long after both have loaded. The parser is fenced so the test
              # harness can evaluate it without the page.
              "\n/*__VOICE_START__*/\n" + open(os.path.join(HERE, "voice.js"), encoding="utf-8").read() +
              "\n/*__VOICE_END__*/\n" +
              # analytics.js (v0.18f) declares `const ANALYTICS`, read by access.js when it
              # loads, so it comes first. It does nothing unless the page is the site build
              # with a PostHog key.
              "\n" + open(os.path.join(HERE, "analytics.js"), encoding="utf-8").read() + "\n" +
              # landing.js (v0.19) declares `const LANDING`, the welcome page, which access.js
              # shows and hides by session. Inert in the local build unless ?landing is given.
              "\n" + open(os.path.join(HERE, "landing.js"), encoding="utf-8").read() + "\n" +
              # access.js (v0.18) declares `const ACCESS_UI`, which ui.js calls from boot() and
              # from chooseCase, so it too comes before ui.js.
              "\n/*__ACCESS_START__*/\n" + open(os.path.join(HERE, "access.js"), encoding="utf-8").read() +
              "\n/*__ACCESS_END__*/\n" +
              # progress.js (28 October 2026) declares `const PROGRESS`, saved runs in the site
              # build. access.js hands it the Supabase client; ui.js calls it. Inert in the
              # local build, where ACCESS.mode is "local".
              "\n" + open(os.path.join(HERE, "progress.js"), encoding="utf-8").read() + "\n" +
              # procedures.js (28 October 2026) declares `const PROCEDURES`, the Procedures box
              # and window. ui.js calls PROCEDURES.init from boot(), so it comes before ui.js.
              # The procedure engine itself is not in this bundle: see load_procedures.
              "\n" + open(os.path.join(HERE, "procedures.js"), encoding="utf-8").read() + "\n" +
              "\n" + open(os.path.join(HERE, "ui.js"), encoding="utf-8").read() + "\n" +
              # pupils.js (19 October 2026) declares `const PUPILVIEW` and reads ST, PT and
              # pupilState at run time, so it comes after ui.js and engine.js.
              "\n" + open(os.path.join(HERE, "pupils.js"), encoding="utf-8").read() + "\n" +
              # v0.18a. Review tools (a clock speed control) go into the local build only.
              # page() fills this marker with review.js there and with nothing in the site.
              "/*__REVIEW_TOOLS__*/\n")

    cfg = json.load(open(SITE_CONFIG, encoding="utf-8"))
    product = cfg["productName"]
    legal = f"© {cfg['copyrightYear']} {cfg['copyrightHolder']}. All rights reserved."
    shell = shell.replace("__PRODUCT__", product.replace("<", ""))
    shell = shell.replace("__ROOM_BG__", room_bg)
    # v0.19. The welcome page's screenshots: real screens from CHFE with the case text blurred,
    # made by engine/assets/landing/README.md's procedure. Public by design.
    for key in ("case", "debrief", "board"):
        shot = os.path.join(HERE, "assets", "landing", key + ".jpg")
        uri = ("data:image/jpeg;base64," + base64.b64encode(open(shot, "rb").read()).decode()) if os.path.exists(shot) else ""
        shell = shell.replace("__LANDING_SHOT_" + key.upper() + "__", uri)
    # The welcome page's logo slot: engine/assets/logo.svg or logo.png when one exists,
    # otherwise the placeholder mark.
    logo_html = '<span class="ld-mark" aria-hidden="true"></span>'
    for ext, mime in (("svg", "image/svg+xml"), ("png", "image/png")):
        lp = os.path.join(HERE, "assets", "logo." + ext)
        if os.path.exists(lp):
            logo_html = ('<img class="ld-logoimg" alt="" src="data:' + mime + ';base64,' +
                         base64.b64encode(open(lp, "rb").read()).decode() + '">')
            break
    shell = shell.replace("__LOGO__", logo_html)
    # The welcome demo's twelve-lead (owner instruction, 28 October 2026): an SVG from the ECG
    # generator, its points thinned to 500 Hz and its pattern ids prefixed with ldecg- so they
    # cannot clash with anything else on the page. Inlined like the other assets.
    ecg_fp = os.path.join(HERE, "assets", "landing-ecg.svg")
    if os.path.exists(ecg_fp):
        ecg_svg = open(ecg_fp, encoding="utf-8").read()
        ecg_svg = re.sub(r"<\?xml[^>]*\?>", "", ecg_svg).strip()
    else:
        print("  warning: engine/assets/landing-ecg.svg is missing; the demo's ECG sheet is empty")
        ecg_svg = '<p style="padding:20px">The ECG could not be loaded.</p>'
    shell = shell.replace("__LD_ECG__", ecg_svg)
    # The interface fonts (author's choice, 28 October 2026): Atkinson Hyperlegible Next and
    # Atkinson Hyperlegible Mono, from engine/assets/fonts/ (see its README for sources and
    # licenses). They are inlined like every other asset, so the page asks no one for a font,
    # the local file works offline, and the policy needs only font-src data:. A missing file
    # leaves its family to the fallbacks in --sans and --mono.
    font_dir = os.path.join(HERE, "assets", "fonts")
    font_faces = [("Atkinson Hyperlegible Next", "normal", "200 800", "atkinson-hyperlegible-next-latin-wght-normal.woff2"),
                  ("Atkinson Hyperlegible Next", "italic", "200 800", "atkinson-hyperlegible-next-latin-wght-italic.woff2"),
                  ("Atkinson Hyperlegible Mono", "normal", "200 800", "atkinson-hyperlegible-mono-latin-wght-normal.woff2")]
    font_css = ""
    for fam, style, weights, fname in font_faces:
        fp = os.path.join(font_dir, fname)
        if not os.path.exists(fp):
            print("  warning: font file missing, the fallback is used: " + os.path.relpath(fp, ROOT))
            continue
        font_css += ("@font-face{font-family:'" + fam + "';font-style:" + style + ";font-weight:" + weights +
                     ";font-display:swap;src:url(data:font/woff2;base64," +
                     base64.b64encode(open(fp, "rb").read()).decode() + ") format('woff2')}\n")
    shell = shell.replace("/*__FONTS__*/", "/* Atkinson Hyperlegible Next and Mono: SIL Open Font License 1.1, "
                          "see engine/assets/fonts/ */\n" + font_css)
    shell = shell.replace("__N_ACTIONS__", str(len(CE))).replace("__N_DIAGNOSES__", str(len(shared["diagnoses"])))
    shell = shell.replace("__HERO_BG__", "data:image/jpeg;base64," + hero_bg)
    shell = shell.replace("__AVATAR_M__", "data:image/png;base64," + avatar_m)
    shell = shell.replace("__AVATAR_F__", "data:image/png;base64," + avatar_f)
    shell = shell.replace("__NURSE_AVATAR__", "data:image/png;base64," + nurse_av)
    shell = shell.replace("__AMBIENCE_JSON__",
                          jsafe("data:audio/mpeg;base64," + ambience) if ambience else '""')
    shell = shell.replace("__VOICE_JSON__", jsafe(voice))
    shell = shell.replace("__SHARED_JSON__", jsafe(shared))
    shell = shell.replace("</script>\n</body>", bundle + "</script>\n</body>")

    if re.search(r"</script", bundle, re.I):
        raise SystemExit("an engine source contains </script, which would end the inline script early")

    review_js = open(os.path.join(HERE, "review.js"), encoding="utf-8").read()
    if re.search(r"</script", review_js, re.I):
        raise SystemExit("review.js contains </script, which would end the inline script early")

    procs, px_code = load_procedures(packs, jsafe)

    def page(title, cases, access, lib, review="", procedures=(), px=""):
        """One finished page. What differs between the local build and the site: the title,
        the cases block, the access block, whether supabase-js is inlined, whether the
        review tools are, and whether the procedures are whole with their code inline (local)
        or stubs whose code is a separate file (site)."""
        out = shell.replace("__TITLE__", title.replace("<", ""))
        out = out.replace("/*__REVIEW_TOOLS__*/\n", review)
        out = out.replace("__ACCESS_JSON__", jsafe(access))
        out = out.replace("<!--__SUPABASE_LIB__-->", lib)
        # Last, so that nothing inside a case pack can be mistaken for one of the markers.
        out = out.replace("__CASES_JSON__", jsafe(cases))
        out = out.replace("__PROCEDURES_JSON__", jsafe(list(procedures)))
        out = out.replace("__PX_CODE__", px)
        return out

    # Case numbers: whole numbers from 1, one per case. Two cases sharing a number would be
    # two "Case 3"s on the list and in a learner's history, so that stops the build.
    _seen_numbers = {}
    for p in packs:
        n = p["card"].get("number")
        if n is None:
            print("  warning: " + p["prefix"] + " has no metadata.case_number (authoring 2.2)")
            continue
        if not isinstance(n, int) or isinstance(n, bool) or n < 1:
            raise SystemExit(p["prefix"] + ": metadata.case_number must be a whole number from 1, not " + repr(n))
        if n in _seen_numbers:
            raise SystemExit("case number " + str(n) + " is used by both " + _seen_numbers[n] + " and " + p["prefix"])
        _seen_numbers[n] = p["prefix"]

    # ---- the local build: every case, no backend. Behaves exactly as before v0.18.
    local_title = (product + " (local build)") if len(packs) != 1 else packs[0]["card"]["title"]
    local = page(local_title, packs, {"mode": "local", "product": product, "legal": legal}, "",
                 review="/*__REVIEW_START__*/\n" + review_js + "\n/*__REVIEW_END__*/\n",
                 procedures=procs, px=px_code)
    os.makedirs(BUILD_DIR, exist_ok=True)
    open(OUT, "w", encoding="utf-8", newline="\n").write(local)
    open(SITE_INDEX, "w", encoding="utf-8", newline="\n").write(local)

    # ---- the deployed site and the private packs. Only from a build of every pack: a site
    # built from a subset would deploy without the missing cases, and nobody would notice.
    if not sys.argv[1:]:
        free = set(cfg.get("freeCases") or [])
        unknown = free - {p["prefix"] for p in packs}
        if unknown:
            raise SystemExit("site-config.json freeCases names no such case: " + ", ".join(sorted(unknown)))
        os.makedirs(PACKS_DIR, exist_ok=True)
        # Files are overwritten, never deleted, so a case that has been removed leaves its old
        # pack behind. Say so, so that it is not uploaded by mistake.
        stale = sorted(f for f in os.listdir(PACKS_DIR)
                       if f.endswith(".json") and f[:-5] not in ({p["prefix"] for p in packs if p["prefix"] not in free} |
                                                                 {p["prefix"] for p in procs}))
        for f in stale:
            print("  warning: private-packs/" + f + " is not from this build; do not upload it")
        site_cases = []
        # Saved progress (28 October 2026). A saved run is its action log, and fold() reads the
        # pack, the engine and the shared catalog. versionKey hashes all three, so a run saved
        # under one build is never resumed under a build that would replay it differently:
        # the site says the case has been improved and the run is deleted (owner decision).
        engine_src = open(os.path.join(HERE, "engine.js"), encoding="utf-8").read()
        shared_src = jsafe(shared)
        def version_key(pack_text):
            return hashlib.sha256((engine_src + "\n" + shared_src + "\n" + pack_text).encode("utf-8")).hexdigest()[:32]
        for p in packs:
            if p["prefix"] in free:
                site_cases.append(dict(p, versionKey=version_key(jsafe(p))))
                continue
            body = jsafe(p).encode("utf-8")
            open(os.path.join(PACKS_DIR, p["prefix"] + ".json"), "wb").write(body)
            pat = p["case"].get("patient") or {}
            # The stub: what the case list shows, and the hash the client checks the loaded
            # pack against. Nothing clinical beyond what the list already displays.
            site_cases.append({
                "prefix": p["prefix"], "locked": True,
                "card": p["card"],
                "patient": {"age": pat.get("age"), "sex": pat.get("sex")},
                "buildNoteCount": len(p["buildNotes"]),
                "packSha256": hashlib.sha256(body).hexdigest(),
                "packBytes": len(body),
                "versionKey": version_key(body.decode("utf-8")),
            })
        check_public_key(cfg.get("supabaseKey", ""), cfg.get("supabaseUrl", ""))
        access = {"mode": "site", "product": product, "legal": legal,
                  "supabaseUrl": cfg.get("supabaseUrl", ""), "supabaseKey": cfg.get("supabaseKey", ""),
                  "edgeFunction": cfg.get("edgeFunction", "case-pack"),
                  "googleSignIn": bool(cfg.get("googleSignIn", False)),
                  "emailSignUp": bool(cfg.get("emailSignUp", False)),
                  "posthogKey": cfg.get("posthogKey", ""), "posthogHost": cfg.get("posthogHost", "")}
        check_posthog(access["posthogKey"], access["posthogHost"])
        # Procedures: the packs go to private-packs/ like a locked case, the site keeps a stub
        # and the hash, and the code is written as site/px/procsim-<hash>.js. The hash in the
        # name means a browser never runs an old copy against a new pack.
        proc_stubs = []
        for pr in procs:
            body = jsafe(pr).encode("utf-8")
            open(os.path.join(PACKS_DIR, pr["prefix"] + ".json"), "wb").write(body)
            proc_stubs.append({"prefix": pr["prefix"], "kind": "procedure", "locked": True, "card": pr["card"],
                               "packSha256": hashlib.sha256(body).hexdigest(), "packBytes": len(body)})
        px_dir = os.path.join(DEPLOY_DIR, "px")
        os.makedirs(px_dir, exist_ok=True)
        px_name = ("procsim-" + hashlib.sha256(px_code.encode("utf-8")).hexdigest()[:16] + ".js") if px_code else ""
        # Older copies are left in place and named, like stale packs: the build never deletes.
        # Remove them before committing site/.
        for f in sorted(os.listdir(px_dir)):
            if re.fullmatch(r"procsim-[0-9a-f]+\.js", f) and f != px_name:
                print("  warning: site/px/" + f + " is not from this build; delete it before committing site/")
        if px_code:
            fp = os.path.join(px_dir, px_name)
            if not (os.path.exists(fp) and open(fp, encoding="utf-8").read() == px_code):
                open(fp, "w", encoding="utf-8", newline="\n").write(px_code)
            access["pxScript"] = "px/" + px_name
        lib_js = open(SUPABASE_JS, encoding="utf-8").read()
        if "</script" in lib_js.lower():
            raise SystemExit("vendored supabase-js contains </script and cannot be inlined")
        lib_notice = open(SUPABASE_LICENSE, encoding="utf-8").read().replace("*/", "* /")
        lib = ("<script>/*\nsupabase-js 2.117.2, https://github.com/supabase/supabase-js\n" +
               lib_notice + "\n*/\n" + lib_js + "\n</script>")
        if access["posthogKey"]:
            ph_js = open(POSTHOG_JS, encoding="utf-8").read()
            if "</script" in ph_js.lower():
                raise SystemExit("vendored posthog-js contains </script and cannot be inlined")
            ph_notice = open(POSTHOG_LICENSE, encoding="utf-8").read().replace("*/", "* /")
            lib += ("\n<script>/*\nposthog-js 1.434.17 (no-external build), https://github.com/PostHog/posthog-js\n" +
                    ph_notice + "\n*/\n" + ph_js + "\n</script>")
        site = page(product, site_cases, access, lib, procedures=proc_stubs, px="")
        # The review tools are for authors and reviewers and never ship.
        if "REVIEW_SPEED" in site or "__REVIEW_START__" in site:
            raise SystemExit("the review tools found their way into the site build")
        # A guard, not a proof: no locked case's phases or interview may appear in the site.
        for p in packs:
            if p["prefix"] in free:
                continue
            for probe in (jsafe(p["case"]["phases"])[:300], jsafe(p["bindings"])[:300]):
                if probe in site:
                    raise SystemExit(p["prefix"] + ": case content found in the site build")
        for pr in procs:
            for probe in (jsafe(pr["steps"])[:300], jsafe(pr["layers"])[:300]):
                if probe in site:
                    raise SystemExit(pr["prefix"] + ": procedure content found in the site build")
        os.makedirs(DEPLOY_DIR, exist_ok=True)
        open(DEPLOY_INDEX, "w", encoding="utf-8", newline="\n").write(site)
        write_headers(site)
        print("wrote", os.path.relpath(DEPLOY_INDEX, ROOT), round(len(site) / 1024), "KB,",
              len(packs) - len(free), "locked,", len(free), "free,", len(procs), "procedures")
        if px_code:
            print("wrote", "site/" + access["pxScript"], round(len(px_code) / 1024), "KB")
        print("wrote", os.path.relpath(PACKS_DIR, ROOT) + "/", "(upload these to the case-packs bucket)")
        if not access["supabaseUrl"] or not access["supabaseKey"]:
            print("  note: site-config.json has no Supabase URL or key yet, so the site will say sign-in is not configured")
    else:
        print("  note: named packs only, so site/ and private-packs/ were not rebuilt")
    shell = local

    print("wrote", os.path.relpath(OUT, ROOT), round(len(shell) / 1024), "KB",
          "(and", os.path.relpath(SITE_INDEX, ROOT) + ")")
    print("catalog:", len(CE), "actions,", len(shared["diagnoses"]), "diagnoses")
    for p in packs:
        print(f"  {p['prefix']:<8} {p['id']:<20} bindings {len(p['bindings']):>3}  "
              f"orphans {len(p['orphans']):>2}  shadowed {len(p['shadowed'])}")
        for n in p["buildNotes"]:
            print(f"           note: {n}")
    return 0


