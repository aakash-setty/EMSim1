def resolve_dx(ref):
    """Catalog id, exact display name, or exact synonym. No guessing: a wrong guess
    scores the handoff against the wrong answer and nothing downstream would notice."""
    if not ref:
        return None
    if ref in DX_IDS:
        return ref
    low = ref.lower()
    for d in shared["diagnoses"]:
        if d["label"].lower() == low or any(s.lower() == low for s in d["syn"]):
            return d["id"]
    return None


# ---------------------------------------------------------------- per case
def build_pack(pack):
    case = json.load(open(pack.case, encoding="utf-8"))
    binding = json.load(open(pack.binding, encoding="utf-8"))
    bindmap = json.load(open(pack.binding_map, encoding="utf-8"))
    notes = []

    # Interview banks. A topic's hand-written `variants` and its generated
    # `expanded_variants` (catalog/expand_interview_variants.py) are one bank at
    # runtime; they are kept apart in the case file so provenance survives and so the
    # generator can replace its own block without touching the author's. Merged here,
    # once, and nothing downstream knows there were two lists.
    for t in case.get("interview", {}).get("topics", []):
        extra = t.pop("expanded_variants", None) or []
        have = {v.lower() for v in t.get("variants", [])}
        for v in extra:
            if v.lower() not in have:
                t.setdefault("variants", []).append(v); have.add(v.lower())

    rows = {r["case_id"]: r for r in binding["rows"]}
    rev = {}                                   # catalog id -> [case ids], case-file order
    for a in case["case_actions"]:
        r = rows.get(a["catalog_id"])
        if r and r.get("catalog_id"):
            rev.setdefault(r["catalog_id"], []).append(a["catalog_id"])

    bindings, shadowed = {}, {}
    for cid, case_ids in rev.items():
        bindings[cid] = case_ids[0]
        for hidden in case_ids[1:]:
            shadowed[hidden] = case_ids[0]

    # also_covers: one case action claiming several catalog entries, so its tag, halt
    # reason and debrief note apply to every route to the same act. Each covered entry
    # keeps its own button and its own catalog name; only the case-specific fields are
    # shared.
    covers = {}
    for r in binding["rows"]:
        for extra in (r.get("also_covers") or []):
            if extra in bindings:
                notes.append(f"{r['case_id']} claims {extra} through also_covers, but "
                             f"{bindings[extra]} already binds it")
                continue
            covers[extra] = r["case_id"]

    orphans = {}
    for r in bindmap.get("rows", []):
        if r.get("catalog_id") is None and r.get("unmatched_placement"):
            p = r["unmatched_placement"]
            orphans[r["case_id"]] = {
                "tab": p["tab"], "group": p.get("group", "Not in the catalog"),
                "category": orphan_category(r["case_id"]),
                "narration_template": r.get("unmatched_narration"),
            }

    unplaced = [a["catalog_id"] for a in case["case_actions"]
                if a["catalog_id"] not in CE
                and a["catalog_id"] not in {v for v in bindings.values()}
                and a["catalog_id"] not in orphans
                and a["catalog_id"] not in shadowed]
    if unplaced:
        notes.append("unmatched case actions with no placement in the binding map, so they are "
                     "unreachable: " + ", ".join(unplaced))

    h = case["handoff"]
    correct_dx = resolve_dx(h["correct_diagnosis"].get("catalog_id")) \
        or resolve_dx(h["correct_diagnosis"].get("label"))
    if not correct_dx:
        notes.append("the correct diagnosis does not resolve to a diagnosis catalog id, so the "
                     "handoff cannot be scored")
    alt_dx = {}
    alt_dx_defensible = []
    for a in h.get("alternative_diagnoses", []):
        hit = resolve_dx(a.get("catalog_id")) or resolve_dx(a.get("label"))
        if hit:
            alt_dx[hit] = a["explanation"]
            # A case whose formulation has two halves has two catalog ids that are both
            # defensible answers, and the engine scores one. Marking the other outright
            # incorrect teaches a learner who understood the case that they did not.
            if a.get("verdict") == "acceptable_with_qualification":
                alt_dx_defensible.append(hit)
        else:
            notes.append("alternative diagnosis %r does not resolve to a catalog id"
                         % a.get("label", a.get("catalog_id")))

    # v0.9. additional_diagnoses: what is also true of the patient and appropriate to
    # name at handover beside the primary. Resolved the same way; an id that is also
    # the correct diagnosis is dropped with a note, because the primary is scored on
    # its own terms and crediting it twice would inflate the handoff score.
    addl_dx = {}
    for a in h.get("additional_diagnoses", []) or []:
        hit = resolve_dx(a.get("catalog_id")) or resolve_dx(a.get("label"))
        if not hit:
            notes.append("additional diagnosis %r does not resolve to a catalog id"
                         % a.get("label", a.get("catalog_id")))
        elif hit == correct_dx:
            notes.append("additional diagnosis %r is the correct diagnosis; ignored" % hit)
        else:
            addl_dx[hit] = a.get("explanation", "")

    # 23 October 2026, author instruction. minor_diagnoses: also true of the patient, but
    # not one of the one or two diagnoses the handover is scored on. Naming one is credited
    # as true and costs nothing; leaving it out costs nothing either. Resolved the same way;
    # an id that is already the primary or an additional diagnosis is dropped with a note.
    minor_dx = {}
    for a in h.get("minor_diagnoses", []) or []:
        hit = resolve_dx(a.get("catalog_id")) or resolve_dx(a.get("label"))
        if not hit:
            notes.append("minor diagnosis %r does not resolve to a catalog id"
                         % a.get("label", a.get("catalog_id")))
        elif hit == correct_dx or hit in addl_dx:
            notes.append("minor diagnosis %r is already scored; ignored" % hit)
        else:
            minor_dx[hit] = a.get("explanation", "")

    disp_labels = {h["correct_disposition"]["id"]: h["correct_disposition"]["label"]}
    for d in h.get("alternative_dispositions", []):
        disp_labels[d["id"]] = d["label"]
    disp_order = h.get("disposition_display_order") or list(disp_labels)
    missing_order = [d for d in disp_labels if d not in disp_order]
    if missing_order:
        notes.append("dispositions missing from disposition_display_order: "
                     + ", ".join(missing_order))
        disp_order = disp_order + missing_order

    m = case["metadata"]
    dbg = case.get("debrief_configuration", {})

    return {
        "prefix": pack.prefix,
        "id": case["case_id"],
        # v0.11. A case may carry images: a twelve-lead tracing, a plain film. They live
        # as ordinary image files in `cases/<PREFIX>/media/` so they can be looked at,
        # replaced and diffed as images, and they are inlined as data URIs here, because
        # the product is one HTML file and a second request for a picture would make it
        # two. The id a case content key names is the file's stem.
        #
        # This is the one thing in a pack whose size a reviewer should watch. DIPH's three
        # images are about 800 KB on disk and about 1.1 MB once base64 has added its third,
        # which is a third of that build. Downscale and recompress before adding more; the
        # ECGs are JPEG at quality 80 and 1446 pixels wide, which is enough to measure a
        # QRS on screen and not enough to print.
        "media": load_media(pack),
        # 19 October 2026 (author instruction). A scan the resident scrolls through: a stack
        # of CT images as Hounsfield units, read by the series viewer in ui.js. On disk it is
        # `media/<stem>.series.json` (the geometry, the windows and the notice) beside
        # `media/<stem>.series.gz` (the voxels). An image payload names it as `series`, and
        # its `image` is the still the record shows as the thumbnail. Watch the size: SCOOT's
        # head CT is about 2.9 MB on disk and about 3.9 MB once base64 has added its third.
        "series": load_series(pack),
        # everything the picker needs, so it does not have to open the case file
        "card": {
            "title": m.get("working_title", case["case_id"]),
            # Case number (author instruction, 28 October 2026): "Case N" on the list, the
            # splash and the learner's history. Permanent, never reused.
            "number": m.get("case_number"),
            # The welcome screen lists the short clinical complaint, not the patient's
            # own words; chief_complaint is the quote and belongs on the splash. Both
            # of these are optional and degrade, so a pack written before them lists.
            "complaint": m.get("complaint") or m.get("working_title", case["case_id"]),
            "category": m.get("category"),
            "chief_complaint": m.get("chief_complaint_patient_voice", ""),
            "setting": (m.get("care_setting") or {}).get("label", ""),
            "target_level": m.get("target_level"),
            "runtime_seconds": m.get("estimated_runtime_seconds"),
            "unreviewed": bool((case.get("provenance") or {}).get("warning")),
        },
        "case": case,
        "bindings": bindings,
        "covers": covers,
        "shadowed": shadowed,
        "orphans": orphans,
        "bindingCounts": binding["counts"],
        "phaseShort": {p["id"]: p.get("short_label") or p.get("label") or p["id"]
                       for p in case["phases"]},
        "traps": dbg.get("trap_actions", []),
        "dispOrder": disp_order,
        "dispLabels": disp_labels,
        "correctDxId": correct_dx,
        "correctDxExplanation": h["correct_diagnosis"].get("explanation", ""),
        "altDx": alt_dx,
        "altDxDefensible": alt_dx_defensible,
        "addlDx": addl_dx,
        "minorDx": minor_dx,
        "promptCap": case.get("prompt_cap_recommendation", {}).get("per_phase", 3),
        "buildNotes": notes,
        # Case discussion, the left column of the debrief (author instruction, 14 October
        # 2026): cases/<PREFIX>/<PREFIX>-discussion.html, an HTML fragment with its figures as
        # inline SVG. Optional. It rides on the pack, so a locked case keeps its discussion
        # in its private pack and the public stub carries none of it.
        "discussion": load_discussion(pack),
    }


def load_discussion(pack):
    """The case discussion fragment, or "" when the case has none. No scripts: the page's
    Content-Security-Policy allows inline scripts by hash only, and a discussion is reading."""
    p = pack.path("discussion.html")
    if not os.path.exists(p):
        return ""
    s = open(p, encoding="utf-8").read()
    if "<script" in s.lower() or re.search(r"\son[a-z]+\s*=", s, re.I):
        raise SystemExit(f"{pack.prefix}: {os.path.basename(p)} may not contain scripts or event handlers")
    return s.strip()


MEDIA_TYPES = {".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".png": "image/png",
               ".webp": "image/webp", ".gif": "image/gif"}


def load_media(pack):
    """Every image in `cases/<PREFIX>/media/`, as {stem: data URI}.

    A pack with no media directory returns an empty map and costs nothing. The stem is
    the id, so two files that differ only in extension would collide; that is refused
    here rather than silently resolving to whichever was read last.
    """
    d = os.path.join(pack.dir, "media")
    if not os.path.isdir(d):
        return {}
    out = {}
    for name in sorted(os.listdir(d)):
        stem, ext = os.path.splitext(name)
        mime = MEDIA_TYPES.get(ext.lower())
        if not mime:
            continue
        if stem in out:
            raise SystemExit(f"{pack.prefix}: two media files share the id {stem!r}")
        with open(os.path.join(d, name), "rb") as f:
            out[stem] = "data:%s;base64,%s" % (mime, base64.b64encode(f.read()).decode())
    return out


SERIES_FORMAT = "emsim-ct-1"


def load_series(pack):
    """Every CT series in `cases/<PREFIX>/media/`, as {stem: geometry plus base64 voxels}.

    A series is two files that share a stem: `<stem>.series.json` and `<stem>.series.gz`.
    One without the other is refused here, as is a format this build does not read, so a
    half-copied series stops the build instead of shipping a viewer that cannot open. The
    voxel count is checked by the validator, which decompresses it; the build only carries
    the bytes."""
    d = os.path.join(pack.dir, "media")
    if not os.path.isdir(d):
        return {}
    names = os.listdir(d)
    stems = sorted({n[:-len(".series.json")] for n in names if n.endswith(".series.json")} |
                   {n[:-len(".series.gz")] for n in names if n.endswith(".series.gz")})
    out = {}
    for stem in stems:
        jp, gp = os.path.join(d, stem + ".series.json"), os.path.join(d, stem + ".series.gz")
        if not (os.path.exists(jp) and os.path.exists(gp)):
            raise SystemExit(f"{pack.prefix}: series {stem!r} needs both {stem}.series.json and {stem}.series.gz")
        meta = json.load(open(jp, encoding="utf-8"))
        if meta.get("format") != SERIES_FORMAT:
            raise SystemExit(f"{pack.prefix}: series {stem!r} is format {meta.get('format')!r}, not {SERIES_FORMAT!r}")
        with open(gp, "rb") as f:
            meta["data"] = base64.b64encode(f.read()).decode()
        out[stem] = meta
    return out


