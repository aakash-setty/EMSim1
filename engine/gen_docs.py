def pack_sources(prefix):
    pk = CasePack(prefix)
    py = sorted(glob.glob(os.path.join(pk.dir, "case_*.py")))
    return py if py else [pk.case]


def generated_span(text):
    start = text.find("# ---- EXPANDED VARIANTS (generated")
    end = text.find("# ---- END EXPANDED VARIANTS", start) if start >= 0 else -1
    if start < 0 or end < 0:
        return (-1, -1)
    return (text[:start].count("\n") + 1, text[:end].count("\n") + 1)


def find_example(regex, prefer, opts):
    pat = re.compile(regex)
    near = re.compile(opts["near"]) if opts.get("near") else None
    not_near = re.compile(opts["not_near"]) if opts.get("not_near") else None
    fpat = re.compile(opts["file"]) if opts.get("file") else None
    for prefix in prefer + [p for p in list_packs() if p not in prefer]:
        if prefix not in list_packs():
            continue
        for f in pack_sources(prefix):
            if fpat and not fpat.search(os.path.basename(f)):
                continue
            text = file_text(f)
            lines = text.splitlines()
            g0, g1 = generated_span(text)
            for i, line in enumerate(lines, 1):
                if g0 <= i <= g1 or line.lstrip().startswith("#"):
                    continue
                if not pat.search(line):
                    continue
                window = "\n".join(lines[max(0, i - 5):i + 4])
                if near and not near.search(window):
                    continue
                if not_near and not_near.search(window):
                    continue
                return os.path.relpath(f, ROOT), i, prefix
    return None, None, None


def mechanism_index(problems):
    out = [GENERATED_BANNER, "# Mechanism index\n\n",
           "Each engine mechanism a case can use, the authoring section that governs it, and one\n"
           "worked example found in the packs now (file and line). Open that file at that line,\n"
           "not another whole pack. Line numbers are recomputed each time this is generated.\n\n",
           "| mechanism | what | section | example |\n|---|---|---|---|\n"]
    for name, what, section, regex, prefer, opts in MECHANISMS:
        f, ln, prefix = find_example(regex, prefer, opts)
        if f is None:
            problems.append(f"mechanism-index: no pack uses '{name}' (pattern {regex!r})")
            ex = "no example in the library yet"
        else:
            ex = f"`{f}:{ln}` ({prefix})"
        out.append(f"| {name} | {what} | {section} | {ex} |\n")
    return "".join(out)


