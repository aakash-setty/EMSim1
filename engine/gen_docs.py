def scan_paths():
    """Every JSON path in every case file, with the packs that use it. Ids under the content
    maps, avatar keys and free-form note blocks are collapsed."""
    paths = {}

    def add(p, pk):
        paths.setdefault(p, set()).add(pk)

    def walk(o, path, pk):
        if isinstance(o, dict):
            # a content key may be a rule list or {rules: [...]}: normalise to .rules[]
            for k, v in o.items():
                kk = k
                if re.fullmatch(r"content_keys\.(exam|labs|imaging|consultants)", path):
                    kk = "<id>"
                elif path == "patient.avatar":
                    kk = "<key>"
                p = f"{path}.{kk}" if path else kk
                if kk == "<id>" and isinstance(v, list):
                    p2 = p + ".rules"
                    add(p2, pk); walk(v, p2, pk); continue
                add(p, pk); walk(v, p, pk)
        elif isinstance(o, list):
            p = path + "[]"
            for x in o:
                walk(x, p, pk)

    for prefix in list_packs():
        pk = CasePack(prefix)
        walk(load_json(pk.case), "", prefix)
    return paths


def note_for(path):
    """The most specific note for a path: exact, then an ancestor's '.*', then an ancestor."""
    if path in FIELDS:
        return FIELDS[path], path
    parts = re.split(r"(?<=\])\.|\.", path)
    ancestors = []
    for i in range(len(parts) - 1, 0, -1):
        anc = ".".join(parts[:i])
        ancestors.append(anc)
        if anc.endswith("[]"):
            ancestors.append(anc[:-2])
    for anc in ancestors:
        if anc + ".*" in FIELDS:
            return FIELDS[anc + ".*"], anc + ".*"
    for anc in ancestors:
        if anc in FIELDS:
            return FIELDS[anc], anc
    return None, None


def is_note_path(path):
    leaf = re.split(r"(?<=\])\.|\.", path)[-1]
    if leaf in NOTE_KEYS or leaf.endswith("_note") or leaf.endswith("_rationale"):
        return True
    return any(path == p or path.startswith(p + ".") or path.startswith(p + "[") for p in NOTE_PATH_PREFIXES)


_file_cache = {}
def file_text(p):
    if p not in _file_cache:
        _file_cache[p] = open(p, encoding="utf-8", errors="replace").read()
    return _file_cache[p]


_code_cache = {}
def code_text(p):
    """The file with comments removed, so a key named only in a comment does not count as read."""
    if p not in _code_cache:
        t = file_text(p)
        if p.endswith((".js", ".mjs")):
            t = re.sub(r"/\*.*?\*/", "", t, flags=re.S)
            t = re.sub(r"(?m)^\s*//.*$", "", t)
        else:
            t = re.sub(r'(?s)"""(?:(?!""").)*"""', "", t)
            t = re.sub(r"(?m)#.*$", "", t)
        _code_cache[p] = t
    return _code_cache[p]


def who_reads(leaf):
    """Which code mentions the key name. A rough signal: generic names are not checked."""
    if leaf in GENERIC or leaf.startswith("<"):
        return "generic"
    pat = re.compile(r"\b" + re.escape(leaf) + r"\b")
    out = []
    for tag, files in (("engine", ENGINE_JS), ("build", BUILD), ("validator", VALIDATOR), ("tools", TOOLS)):
        if any(pat.search(code_text(f)) for f in files):
            out.append(tag)
    return "+".join(out) if out else "none"


def field_reference(problems):
    paths = scan_paths()
    rows = []
    seen_notes = set()
    for path in sorted(paths):
        leaf = re.split(r"(?<=\])\.|\.", path)[-1]
        # containers whose children are listed are not rows themselves
        if any(q != path and (q.startswith(path + ".") or q.startswith(path + "[")) for q in paths):
            continue
        if is_note_path(path) and path not in FIELDS:
            note, matched = ("never", "", "Reviewer note. Nothing reads it"), "(note key)"
        else:
            note, matched = note_for(path)
        if note is None:
            if False:
                pass
            else:
                problems.append(f"field-reference: no note for {path} (used by {', '.join(sorted(paths[path]))}). Add it to engine/field_notes.py")
                note, matched = ("?", "?", "NOT DESCRIBED"), "(missing)"
        seen_notes.add(matched)
        sees, section, text = note
        reads = who_reads(leaf)
        # cross-check the note against the scan
        if reads != "generic" and matched != "(note key)":
            if sees != "never" and "engine" not in reads and "build" not in reads and sees != "no":
                problems.append(f"field-reference: {path}: the note says the learner sees it ({sees}) but no engine or build file mentions `{leaf}`")
            if sees == "never" and ("engine" in reads or "build" in reads):
                problems.append(f"field-reference: {path}: the note says nothing reads it but `{leaf}` appears in {reads}")
        for w in sees.split("+"):
            if w not in SEES_WORDS and w != "?":
                problems.append(f"field_notes: {matched}: unknown SEES word {w!r}")
        rows.append((path, reads, sees, section, text, len(paths[path])))
    for k in FIELDS:
        if k not in seen_notes and not k.endswith(".*"):
            leaf = re.split(r"(?<=\])\.|\.", k)[-1]
            if who_reads(leaf) == "none":
                problems.append(f"field_notes: {k} matches no field in any pack and no code reads `{leaf}` (stale, or a typo)")
    out = [GENERATED_BANNER, "# Case file field reference\n\n",
           "Every field found in a case file, what reads it, where the learner meets it, and the\n"
           "section of `docs/case-authoring-requirements.md` that governs it. Generated from the\n"
           "packs and `engine/field_notes.py`; the 'reads' column is a scan of the code for the\n"
           "field's name (generic names such as `id` and `when` are not scanned).\n\n",
           "**How to read 'sees'.** `splash` before Begin. `list` on the case list. `history` the\n"
           "History tab. `monitor`, `figure`, `sound` the room. `chart` the running record and the\n"
           "exam, results and consult panels. `nurse` the nurse's line. `button` an action or\n"
           "handoff button. `debrief` after the run. `end` the end screen. `no` acts but is never\n"
           "printed. `never` nothing reads it: a note to the reviewing physician.\n\n",
           "**Fields that are notes.** Any key named `note`, `notes`, `authoring_note`,\n"
           "`author_note`, `author_rationale`, `verify`, `rationale`, `source`, or ending in\n"
           "`_note`, is free text for the reviewer wherever it appears. Nothing reads it. Write it\n"
           "freely and keep clinical reasoning for the reviewer there, not in a learner-visible\n"
           "field. Free-form blocks (`phase_notes`, `interview.authoring_notes`, `provenance`,\n"
           "`authored_against`, `catalog_change_requests`) are the same.\n\n",
           "| field | reads | sees | section | what it does |\n|---|---|---|---|---|\n"]
    for path, reads, sees, section, text, n in rows:
        out.append(f"| `{path}` | {reads} | {sees} | {section} | {text} |\n")
    out.append(f"\n{len(rows)} fields across {len(list_packs())} packs, as of the last generation.\n")
    return "".join(out)


