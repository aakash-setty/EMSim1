LIBRARY_DIMS = ["tempo", "uncertainty", "right_answer", "danger", "setting", "feel"]


def uses(case):
    """Which mechanisms a case file uses, by inspecting the structures (not by substring)."""
    u = []
    timed = [t for p in case["phases"] for t in p.get("transitions", []) if t.get("after_seconds") is not None]
    if any(t.get("measured_from") != "guard_true" and (t.get("when") is None or "NOT" in str(t.get("when"))) for t in timed):
        u.append("clock")
    if any(t.get("measured_from") == "guard_true" for t in timed):
        u.append("delayed consequences")
    acts = case.get("case_actions", [])
    def has(key): return any(a.get(key) for a in acts)
    if has("vital_effects"): u.append("vital effects")
    if has("flags_set_timed"): u.append("expiring flags")
    if has("flags_set_repeat"): u.append("repeat dose")
    if has("also_satisfies"): u.append("conditional credit")
    if any(p.get("inherit_vitals") for p in case["phases"]): u.append("inherit vitals")
    if (case.get("handoff") or {}).get("disposition_intercepts"): u.append("intercept")
    if any(any(r.get("value") == "harmful" for r in (a.get("tag") or []) if isinstance(r, dict)) for a in acts): u.append("harmful halt")
    if has("prerequisite_overrides"): u.append("waived prerequisite")
    ck = case.get("content_keys") or {}
    def rules_of(v): return v.get("rules", []) if isinstance(v, dict) else (v or [])
    for sect in ("labs", "imaging"):
        for v in (ck.get(sect) or {}).values():
            if any(isinstance(r.get("value"), dict) and r["value"].get("kind") == "image" for r in rules_of(v) if isinstance(r, dict)):
                if "images" not in u: u.append("images")
    return u


def case_index(problems):
    out = [GENERATED_BANNER, "# Case index\n\n",
           "One line per case in the library, so a new case can say how it differs from every\n"
           "case we have (design guide, 'Choosing a case') without opening any of them. The six\n"
           "variety dimensions come from `metadata.library` in each case; a blank means the pack\n"
           "has not stated it yet. Nothing here has been reviewed by a physician unless the pack's\n"
           "SEED says so.\n\n",
           "| prefix | complaint | category | diagnosis | phases | mechanisms | tempo | uncertainty | right answer | danger | setting | feel |\n"
           "|---|---|---|---|---|---|---|---|---|---|---|---|\n"]
    for prefix in list_packs():
        c = load_json(CasePack(prefix).case)
        m = c.get("metadata", {})
        lib = m.get("library") or {}
        missing = [d for d in LIBRARY_DIMS if not lib.get(d)]
        if missing:
            problems.append(f"case-index: {prefix} states no metadata.library.{'/'.join(missing)} (warning: the case index is blank there)")
        dx = (c.get("handoff", {}).get("correct_diagnosis") or {}).get("catalog_id", "")
        out.append("| {p} | {comp} | {cat} | `{dx}` | {n} | {mech} | {dims} |\n".format(
            p=prefix, comp=m.get("complaint") or m.get("working_title", ""), cat=m.get("category", ""), dx=dx,
            n=len([x for x in c["phases"] if not x.get("terminal")]), mech=", ".join(uses(c)) or "none",
            dims=" | ".join(str(lib.get(d, "")) for d in LIBRARY_DIMS)))
    out.append(f"\n{len(list_packs())} cases, as of the last generation.\n")
    return "".join(out)


# ------------------------------------------------------------------ main
def main():
    check = "--check" in sys.argv
    problems = []
    outputs = {
        "field-reference.md": field_reference(problems),
        "action-index.md": action_index(),
        "diagnosis-index.md": diagnosis_index(),
        "mechanism-index.md": mechanism_index(problems),
        "case-index.md": case_index(problems),
    }
    hard = [p for p in problems if "(warning" not in p]
    soft = [p for p in problems if "(warning" in p]
    changed = []
    for name, text in outputs.items():
        p = os.path.join(OUT, name)
        old = open(p, encoding="utf-8").read() if os.path.exists(p) else None
        if old != text:
            changed.append(name)
            if not check:
                os.makedirs(OUT, exist_ok=True)
                with open(p, "w", encoding="utf-8") as f:
                    f.write(text)
    for s in soft:
        print("warning:", s)
    for h in hard:
        print("ERROR:", h)
    if check:
        for name in changed:
            print(f"ERROR: docs/generated/{name} is stale. Run python3 engine/gen_docs.py")
        print(f"{len(hard) + len(changed)} errors, {len(soft)} warnings")
        return 1 if (hard or changed) else 0
    for name in outputs:
        print(("wrote " if name in changed else "unchanged ") + f"docs/generated/{name}")
    print(f"{len(hard)} errors, {len(soft)} warnings")
    return 1 if hard else 0


if __name__ == "__main__":
    sys.exit(main())
