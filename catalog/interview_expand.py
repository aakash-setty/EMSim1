"""Expand a case's interview topics from the shared phrasing library. A library, not a
command: `cases/<PREFIX>/build_case.py` calls it at build time, with the pack's own topic
map, so adding a case edits nothing outside the pack's folder.

    from interview_expand import expand_topics, apply_expansion, tune_file
    r = expand_topics("PE", TOPICS, TOPIC_MAP, EXTRA_COVERED, pack_dir)
    apply_expansion(TOPICS, r)          # sets expanded_variants and variants_provenance
    json.dump(tune_file("PE", r), ...)  # PE-matcher-tune-questions.json

What a pack supplies, in its `case_4_interview.py`:

  TOPIC_MAP       topic id -> list of concept names in catalog/interview_phrasings.py.
                  A topic absent from the map stays hand-authored.
  EXTRA_COVERED   concept names and cover tags the pack's answers cover without drawing
                  phrasings from (a chest pain topic that answers location and radiation
                  because the pain does not exist). Used only to filter the out-of-scope
                  bank. A tag here must be a concept or a tag in BANK_ONLY_TAGS in
                  catalog/interview_out_of_scope.py. List one only when an authored answer
                  really covers the question.

What it returns, in one dict:

  added           topic id -> new phrasings for the topic's bank
  oos_bank        the out-of-scope bank: questions the case has no answer to, filtered to
                  the concepts the case does not cover
  tune            the withheld slice: every HOLD_EVERY-th new phrasing per topic and every
                  HOLD_EVERY-th out-of-scope entry, kept out of both banks so thresholds
                  can be tuned on them
  dropped         (topic, phrasing, why) for every phrasing refused

Three rules it enforces rather than trusts:
  1. Nothing written into a bank may match a held-out evaluation question
     (<PREFIX>-matcher-eval-questions.json), normalised. Such a phrasing is dropped and
     reported. The evaluation harness checks again.
  2. A phrasing lives in exactly one topic per pack. If it already sits in another
     topic's bank it is not added to this one.
  3. The tuning slice is chosen by position, not by hand, so nobody picks the easy ones.

Deterministic: the same topics, map and library give the same output, byte for byte. The
expansion is recomputed on every build and nothing is stored between builds.

The frozen packs (AFRVR, CHFE, DIPH, MGCA) do not use this at build time: their committed
expansions were edited by hand afterwards and are kept as committed. The command
catalog/expand_interview_variants.py still holds their maps, for --dry-run reports.
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from interview_phrasings import CONCEPTS, OPENERS          # noqa: E402
from interview_out_of_scope import OUT_OF_SCOPE, BANK_ONLY_TAGS   # noqa: E402

HOLD_EVERY = 6            # every 6th new phrasing per topic goes to the tuning set
OPENER_CORES = 3          # phrasings per topic that also get conversational openers
OPENERS_PER_CORE = 2      # openers applied to each of those, rotating through OPENERS

# No date in this text. It said "in Sep 2026" and was stamped on banks generated in October.
PROVENANCE = ("Expanded by catalog/expand_interview_variants.py from catalog/interview_phrasings.py. "
              "The added phrasings were written by an AI assistant, not by a physician, "
              "and mix lay paraphrase, clinical shorthand and conversational forms. Every sixth new "
              "phrasing was withheld into the pack's tuning set rather than added here.")

OOS_BANK_NOTE = (
    "Questions this case has no authored answer to, from catalog/interview_out_of_scope.py filtered "
    "to the concepts this case does not cover. The matcher embeds them beside the topic bank; a "
    "question closer to one of these than to any topic gets the out-of-scope fallback rather than "
    "the nearest topic's answer.")

TUNE_STATUS = ("TUNING SET. Generated by catalog/expand_interview_variants.py: every sixth new phrasing "
               "per topic and every sixth out-of-scope entry, withheld from the banks. Sweep thresholds "
               "against this file and quote the held-out file, never the other way round.")


def norm(s):
    return re.sub(r"[^a-z0-9]+", " ", str(s).lower()).strip()


def held_out_questions(prefix, pack_dir):
    p = os.path.join(pack_dir, f"{prefix}-matcher-eval-questions.json")
    if not os.path.exists(p):
        return set()
    with open(p) as f:
        return {norm(q["q"]) for q in json.load(f)["questions"]}


def with_openers(q):
    """Conversational forms of a full question. Only applied to real questions, never
    to shorthand, and the opener rotation is deterministic in the phrasing text."""
    if len(q) < 14 or not q.endswith("?") or q.lower() == q:
        return []
    body = q[0].lower() + q[1:]
    start = sum(map(ord, q)) % len(OPENERS)
    out = []
    for k in range(OPENERS_PER_CORE):
        t = OPENERS[(start + k * 3) % len(OPENERS)]
        out.append(t.replace("{q}", body).replace("{Q}", q))
    return out


def check_names(prefix, topics, topic_map, extra_covered):
    """Every topic in the map exists, and every concept and cover tag is a known name."""
    known = set(CONCEPTS) | set(BANK_ONLY_TAGS)
    bad = [c for cs in topic_map.values() for c in cs if c not in CONCEPTS]
    bad += [c for c in extra_covered if c not in known]
    bad += [c for _, covers in OUT_OF_SCOPE for c in covers if c not in known]
    if bad:
        raise SystemExit(f"{prefix}: unknown concept or cover tag: " + ", ".join(sorted(set(bad))))
    missing = sorted(set(topic_map) - {t["topic"] for t in topics})
    if missing:
        raise SystemExit(f"{prefix}: TOPIC_MAP names topics the pack does not have: " + ", ".join(missing))


def expand_topics(prefix, topics, topic_map, extra_covered, pack_dir):
    """The expansion, as a value. Does not modify `topics`."""
    check_names(prefix, topics, topic_map, extra_covered)
    held = held_out_questions(prefix, pack_dir)
    covered = set(extra_covered)
    for cs in topic_map.values():
        covered.update(cs)

    # Everything already in a bank, so a phrasing lands in exactly one topic. A topic's
    # own previously expanded list is NOT counted: it is recomputed and replaced, which is
    # what makes a re-run idempotent rather than cumulative.
    owner = {}
    for t in topics:
        for f in [t["canonical"]] + list(t.get("variants", [])):
            owner.setdefault(norm(f), t["topic"])
    prior = {t["topic"]: {norm(f) for f in t.get("expanded_variants", [])} for t in topics}

    added, tune, dropped = {}, [], []
    for t in topics:
        tid = t["topic"]
        if tid not in topic_map:
            continue
        pool = []
        for c in topic_map[tid]:
            for q in CONCEPTS[c]:
                pool.append(q)
        # conversational openers on the first few real questions
        cores = [q for q in pool if len(q) >= 14 and q.endswith("?")][:OPENER_CORES]
        for q in cores:
            pool.extend(with_openers(q))
        fresh, seen = [], set()
        for q in pool:
            n = norm(q)
            if not n or n in seen:
                continue
            seen.add(n)
            if n in held:
                dropped.append((tid, q, "held-out eval question")); continue
            if n in owner and owner[n] != tid:
                dropped.append((tid, q, f"already in {owner[n]}")); continue
            if n in owner and owner[n] == tid:
                continue   # already hand-authored on this topic
            if any(n in prior[o] for o in prior if o != tid):
                dropped.append((tid, q, "expanded on another topic")); continue
            fresh.append(q)
        bank, held_slice = [], []
        for i, q in enumerate(fresh):
            (held_slice if (i + 1) % HOLD_EVERY == 0 else bank).append(q)
        for q in bank:
            owner[norm(q)] = tid
        added[tid] = bank
        tune.extend({"register": "expansion", "q": q, "expect": tid} for q in held_slice)

    # out-of-scope bank, filtered to what this case does not author
    oos_all = [q for q, covers in OUT_OF_SCOPE if not (set(covers) & covered)]
    oos_bank, oos_tune = [], []
    for i, q in enumerate(oos_all):
        n = norm(q)
        if n in held:
            dropped.append(("out_of_scope", q, "held-out eval question")); continue
        if n in owner:
            dropped.append(("out_of_scope", q, f"already in {owner[n]}")); continue
        ((oos_tune if (i + 1) % HOLD_EVERY == 0 else oos_bank)).append(q)
    tune.extend({"register": "out_of_scope_expansion", "q": q, "expect": None} for q in oos_tune)

    return {"prefix": prefix, "added": added, "oos_bank": oos_bank, "tune": tune, "dropped": dropped}


def report(r, verbose=True):
    """One summary line, plus one line per dropped phrasing when verbose."""
    n_new = sum(len(v) for v in r["added"].values())
    lines = [f"{r['prefix']}: {len(r['added'])} topics expanded, +{n_new} variants, "
             f"{len(r['oos_bank'])} out-of-scope bank entries, {len(r['tune'])} tuning questions, "
             f"{len(r['dropped'])} dropped"]
    if verbose:
        lines += [f"   dropped [{tid}] {q!r}: {why}" for tid, q, why in r["dropped"]]
    return "\n".join(lines)


def apply_expansion(topics, r):
    """Set expanded_variants and variants_provenance on each expanded topic, in place.
    build_simulator.py merges expanded_variants into variants at build time, so nothing
    at runtime changes. The hand-written `variants` are never touched."""
    for t in topics:
        t.pop("expanded_variants", None)
        t.pop("variants_provenance", None)
        if r["added"].get(t["topic"]):
            t["expanded_variants"] = list(r["added"][t["topic"]])
            t["variants_provenance"] = PROVENANCE
    return topics


def tune_file(prefix, r):
    """The contents of <PREFIX>-matcher-tune-questions.json."""
    return {"case_prefix": prefix, "status": TUNE_STATUS, "questions": r["tune"]}
